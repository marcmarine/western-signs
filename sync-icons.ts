// Copies the icons from the astroicons repository into src/data/symbols.ts.
// Usage: bun sync-icons.ts [ref], where ref is a tag, branch or commit of astroicons (default: main)
import * as fs from 'fs'
import * as path from 'path'
import { ANGLES, ASPECTS, PLANETS, SIGNS } from './src/data/constants'

const REPOSITORY = 'marcmarine/astroicons'
const outputFilePath: string = path.resolve(
  import.meta.dir,
  'src',
  'data',
  'symbols.ts'
)

// Only the icons of what the library knows about, so `getSymbol` accepts no other name
const ICONS: string[] = [
  ...Object.values(SIGNS),
  ...Object.values(PLANETS),
  ...Object.values(ASPECTS),
  ...Object.values(ANGLES)
].sort()

function parseSVG(content: string): string {
  const pathMatches = [...content.matchAll(/<path[^>]*\sd="([^"]+)"/g)]
  const paths = pathMatches.map(match => match[1]!)

  return paths.join(',')
}

async function request(url: string): Promise<Response> {
  const response = await fetch(url)

  if (!response.ok) {
    throw new Error(`${response.status} ${response.statusText}: ${url}`)
  }

  return response
}

// The exact commit, so the generated file says where it comes from even when given a branch
async function resolveCommit(ref: string): Promise<string> {
  const response = await request(
    `https://api.github.com/repos/${REPOSITORY}/commits/${ref}`
  )
  const { sha } = (await response.json()) as { sha: string }

  return sha
}

const ref: string = process.argv[2] ?? 'main'
const commit: string = await resolveCommit(ref)

const icons: Record<string, string> = {}

for (const name of ICONS) {
  const response = await request(
    `https://raw.githubusercontent.com/${REPOSITORY}/${commit}/icons/${name}.svg`
  )
  const paths = parseSVG(await response.text())

  if (!paths) throw new Error(`Icon "${name}" has no paths.`)

  icons[name] = paths
}

const outputContent: string =
  `// This file was generated by sync-icons.ts from ${REPOSITORY}@${commit} (${ref}). Do not edit.\n\n` +
  `export const SYMBOLS = ${JSON.stringify(icons, null, 2)} as const\n`

fs.writeFileSync(outputFilePath, outputContent)

console.log(`Copied ${ICONS.length} icons from ${REPOSITORY}@${commit} (${ref}).`)
